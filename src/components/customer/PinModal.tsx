'use client';
import { useState } from 'react';
import { Lock, User, Phone, Sparkles } from 'lucide-react';
import { TableSession } from '@/types/database';

interface PinModalProps {
  session: TableSession;
  tableId: number;
  onSuccess: (userData: { name: string; phone: string; pin: string }) => void;
  onResetTable?: () => void;
}

export default function PinModal({ session, tableId, onSuccess }: PinModalProps) {
  const isOccupied = session.status === 'ACTIVE';

  // Automatically generate a 4-digit PIN when the modal loads for an idle table
  const [autoGeneratedPin] = useState<string>(() =>
    Math.floor(1000 + Math.random() * 9000).toString()
  );

  const [enteredPin, setEnteredPin] = useState('');
  const [name, setName] = useState('');
  const [phone, setPhone] = useState('');
  const [error, setError] = useState('');

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setError('');

    if (isOccupied) {
      const cleanPin = enteredPin.trim();
      if (cleanPin.length !== 4) {
        setError('Please enter a 4-digit PIN');
        return;
      }

      if (cleanPin === session.current_pin) {
        onSuccess({
          name: session.customer_name || 'Guest',
          phone: session.customer_phone || '',
          pin: cleanPin,
        });
      } else {
        setError(`Incorrect PIN for Table ${tableId}. Check the host's phone screen.`);
      }
    } else {
      if (!name.trim() || phone.trim().length < 10) {
        setError('Please enter your Name and a valid 10-digit Phone Number');
        return;
      }

      // Automatically pass the system-generated PIN
      onSuccess({
        name: name.trim(),
        phone: phone.trim(),
        pin: autoGeneratedPin,
      });
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-cafe-midnightNavy/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-cafe-ivory border border-cafe-warmGrey w-full max-w-sm rounded-2xl p-6 shadow-2xl">
        {/* Header */}
        <div className="flex items-center justify-between mb-3">
          <div className="flex items-center gap-2">
            <div className="p-2 bg-cafe-oat rounded-lg text-cafe-clay">
              <Lock className="w-5 h-5" />
            </div>
            <h2 className="font-heading font-bold text-xl text-cafe-deepEspresso">
              Table {tableId}
            </h2>
          </div>
          <span
            className={`text-[10px] font-bold px-2 py-0.5 rounded-full ${
              isOccupied ? 'bg-amber-100 text-amber-900' : 'bg-emerald-100 text-emerald-800'
            }`}
          >
            {isOccupied ? 'Occupied' : 'Available'}
          </span>
        </div>

        <p className="text-xs text-cafe-espresso/80 mb-5">
          {isOccupied
            ? `Table ${tableId} is already in session. Enter the table's 4-digit PIN to join.`
            : 'Welcome to Lara’s Cafe! Enter your details to start this table.'}
        </p>

        {error && (
          <div className="p-3 mb-4 text-xs font-semibold bg-red-100 text-red-800 rounded-lg">
            {error}
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          {!isOccupied ? (
            <>
              {/* Customer Details */}
              <div>
                <label className="text-xs font-semibold uppercase text-cafe-espresso/70">
                  Your Name
                </label>
                <div className="relative mt-1">
                  <User className="absolute left-3 top-3 w-4 h-4 text-cafe-warmGrey" />
                  <input
                    type="text"
                    required
                    value={name}
                    onChange={(e) => setName(e.target.value)}
                    placeholder="e.g. Alex"
                    className="w-full pl-9 pr-3 py-2 bg-white border border-cafe-warmGrey rounded-lg focus:outline-none focus:ring-2 focus:ring-cafe-clay text-sm text-cafe-espresso"
                  />
                </div>
              </div>

              <div>
                <label className="text-xs font-semibold uppercase text-cafe-espresso/70">
                  Phone Number
                </label>
                <div className="relative mt-1">
                  <Phone className="absolute left-3 top-3 w-4 h-4 text-cafe-warmGrey" />
                  <input
                    type="tel"
                    required
                    value={phone}
                    onChange={(e) => setPhone(e.target.value)}
                    placeholder="10-digit mobile"
                    className="w-full pl-9 pr-3 py-2 bg-white border border-cafe-warmGrey rounded-lg focus:outline-none focus:ring-2 focus:ring-cafe-clay text-sm text-cafe-espresso"
                  />
                </div>
              </div>

              {/* Generated Passcode Display Card */}
              <div className="bg-cafe-oat/50 border border-cafe-warmGrey/60 rounded-xl p-3 text-center">
                <div className="flex items-center justify-center gap-1.5 text-[11px] font-bold text-cafe-clay uppercase tracking-wider mb-1">
                  <Sparkles className="w-3.5 h-3.5" /> Generated Table PIN
                </div>
                <div className="font-mono text-3xl font-black text-cafe-deepEspresso tracking-widest my-1">
                  {autoGeneratedPin}
                </div>
                <p className="text-[10px] text-cafe-espresso/60">
                  Your friends will enter this PIN on their phones to join your table tab.
                </p>
              </div>

              <button
                type="submit"
                className="w-full py-3 bg-cafe-clay hover:bg-cafe-rosewood text-white font-semibold rounded-xl transition duration-150 shadow-md text-sm cursor-pointer"
              >
                Start Table Tab
              </button>
            </>
          ) : (
            <>
              {/* Join Active Session */}
              <div>
                <label className="text-xs font-semibold uppercase text-cafe-espresso/70 block mb-1">
                  Enter 4-Digit Table PIN
                </label>
                <input
                  type="text"
                  inputMode="numeric"
                  pattern="[0-9]*"
                  maxLength={4}
                  required
                  value={enteredPin}
                  onChange={(e) => setEnteredPin(e.target.value.replace(/\D/g, ''))}
                  placeholder="••••"
                  className="w-full tracking-widest text-center text-2xl font-mono font-bold py-2.5 bg-white border-2 border-cafe-warmGrey rounded-lg focus:outline-none focus:border-cafe-clay text-cafe-deepEspresso"
                />
                <p className="text-[10px] text-cafe-espresso/60 text-center mt-1">
                  Look at the top-right corner of the person who opened Table {tableId}.
                </p>
              </div>

              <button
                type="submit"
                className="w-full py-3 bg-cafe-clay hover:bg-cafe-rosewood text-white font-semibold rounded-xl transition duration-150 shadow-md text-sm cursor-pointer"
              >
                Join Table
              </button>
            </>
          )}
        </form>
      </div>
    </div>
  );
}